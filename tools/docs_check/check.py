#!/usr/bin/env python3
"""Check documentation consistency in the Flytex Camera repo.

Usage::

    python tools/docs_check/check.py [--root .] [--json]

Rules checked
-------------
1. Every file listed in the ``README.md`` table of contents exists, and every
   ``docs/*.md`` file is listed there.  Files whose first two lines contain
   ``AUTOGENERATED`` / ``(sinh tự động)`` and files explicitly marked with
   ``<!-- docs-check: ignore -->`` are exempt from being listed.
2. Every ``M-xx`` / ``R-xx`` / ``O-xx`` / ``D-xx`` reference in the repository
   has a row in the matching registry table: docs/08 for M, docs/10 for R,
   docs/11 for O and D.  ``.git``, ``build`` and ``__pycache__`` are skipped.
3. Relative markdown links to a ``.md`` file that does not exist are errors.
4. Every markdown table data row has the same number of cells as its header
   row.  Separator rows are ignored.
5. Files under ``spec/generated/`` carry a marker in the first two lines so a
   hand edit is obvious.  ``.json`` / ``.csv`` files are exempt because those
   formats cannot carry a comment; ``spec/generate.py --check`` covers them.

Console output is ASCII: ``OK: ...`` on success, ``LOI: <file>:<line> ...``
for each problem.  ``--json`` prints the same result as ASCII JSON.  Exit code
is 1 when at least one error is found.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from urllib.parse import unquote

SKIP_DIRS = frozenset(
    {
        ".git",
        "build",
        "__pycache__",
        ".venv",
        "venv",
        "node_modules",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
    }
)

#: Files that are normally text and worth scanning for ID references.
TEXT_SUFFIXES = frozenset(
    {
        ".md",
        ".markdown",
        ".txt",
        ".py",
        ".c",
        ".h",
        ".toml",
        ".json",
        ".jsonl",
        ".csv",
        ".yml",
        ".yaml",
        ".ini",
        ".cfg",
        ".conf",
        ".sh",
        ".ps1",
        ".bat",
        ".cmake",
        ".mk",
        ".html",
        ".xml",
    }
)

MAX_TEXT_BYTES = 2_000_000
MAX_MARKDOWN_BYTES = 2_000_000

LINK_RE = re.compile(r"\[[^\]]*\]\(([^)]+)\)")
FENCE_RE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")
HEADING_RE = re.compile(r"^\s{0,3}(#{1,6})\s+(.*)$")
INLINE_CODE_RE = re.compile(r"`[^`]*`")
IGNORE_RE = re.compile(r"<!--\s*docs-check:\s*ignore\s*-->", re.IGNORECASE)
SEPARATOR_CELL_RE = re.compile(r"^:?-{3,}:?$")
SCHEME_RE = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:")

REGISTRIES = (
    ("M", "docs/08-kiem-chung.md", re.compile(r"^M-\d{2,3}$"),
     re.compile(r"\bM-\d{2,3}\b")),
    ("R", "docs/10-rui-ro.md", re.compile(r"^R-\d{2}$"),
     re.compile(r"\bR-\d{2}\b")),
    ("O", "docs/11-nhat-ky-quyet-dinh.md", re.compile(r"^O-\d{2}$"),
     re.compile(r"\bO-\d{2}\b")),
    ("D", "docs/11-nhat-ky-quyet-dinh.md", re.compile(r"^D-\d{2}$"),
     re.compile(r"\bD-\d{2}\b")),
)

GENERATED_MARKERS = ("autogenerated", "sinh tự động", "sinh tu dong")
TOC_WORDS = ("mục lục", "muc luc")


def _ascii(text: object) -> str:
    """Return ``text`` as ASCII, escaping anything else."""
    return str(text).encode("ascii", "backslashreplace").decode("ascii")


@dataclass(frozen=True, order=True)
class CheckError:
    """One documentation problem."""

    file: str
    line: int
    rule: str
    message: str

    def text(self) -> str:
        return f"LOI: {self.file}:{self.line} {self.message}"


def split_cells(line: str) -> list[str]:
    """Split a markdown table row into stripped cells.

    Escaped pipes (``\\|``) stay inside their cell.  Leading and trailing
    pipes are optional and are not counted as empty cells.
    """
    text = line.strip()
    if "|" not in text:
        return []
    parts = re.split(r"(?<!\\)\|", text)
    if parts and parts[0].strip() == "":
        parts = parts[1:]
    if parts and parts[-1].strip() == "":
        parts = parts[:-1]
    return [part.strip() for part in parts]


def is_separator(line: str) -> bool:
    """True for a markdown table separator row such as ``|---|:---:|``."""
    if "|" not in line:
        return False
    cells = split_cells(line)
    if not cells:
        return False
    return all(SEPARATOR_CELL_RE.match(cell) for cell in cells)


def _is_table_row(line: str) -> bool:
    """True when the line looks like a table row and is not a code block.

    Leading pipes are optional (``A | B`` is valid markdown too); a heading
    that happens to contain a pipe is not a row.
    """
    stripped = line.lstrip(" ")
    indent = len(line) - len(stripped)
    if indent > 3:
        return False
    if "|" not in stripped:
        return False
    return HEADING_RE.match(stripped) is None


def fence_mask(lines: list[str]) -> list[bool]:
    """Mark lines that belong to a fenced code block (including the fences)."""
    mask = [False] * len(lines)
    fence_char: str | None = None
    fence_len = 0
    for index, line in enumerate(lines):
        match = FENCE_RE.match(line)
        if fence_char is None:
            if match is not None:
                marker = match.group(1)
                fence_char = marker[0]
                fence_len = len(marker)
                mask[index] = True
            continue
        mask[index] = True
        if (
            match is not None
            and match.group(1)[0] == fence_char
            and len(match.group(1)) >= fence_len
        ):
            fence_char = None
            fence_len = 0
    return mask


def parse_link_target(raw: str) -> str | None:
    """Extract a relative link target, or ``None`` for anchors/URLs.

    Handles angle brackets, optional markdown titles and percent encoding.
    """
    target = raw.strip()
    if not target:
        return None
    if target.startswith("<"):
        end = target.find(">")
        if end == -1:
            return None
        target = target[1:end].strip()
    else:
        # Drop an optional title: [x](file.md "title").
        target = target.split()[0] if target.split() else ""
    target = target.strip().strip("\"'")
    if not target or target.startswith("#"):
        return None
    if target.startswith("//") or target.startswith("/"):
        return None
    if SCHEME_RE.match(target):
        return None
    target = target.replace("\\", "/")
    target = unquote(target)
    target = target.split("#", 1)[0].split("?", 1)[0]
    if not target:
        return None
    return target


class Checker:
    """Run all documentation checks against one root directory."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()
        self.errors: list[CheckError] = []
        self._seen: set[tuple[str, int, str, str]] = set()
        self._toc_links: set[tuple[str, int, str]] = set()
        self.markdown_files = self._collect_markdown()
        self.text_files = self._collect_text()
        self.table_count = 0
        self.generated_skipped = 0

    # ------------------------------------------------------------------
    # helpers
    # ------------------------------------------------------------------
    def rel(self, path: Path) -> str:
        try:
            return path.resolve().relative_to(self.root).as_posix()
        except ValueError:
            return _ascii(path)

    def add(self, file: str, line: int, rule: str, message: str) -> None:
        message = _ascii(message)
        key = (file, line, rule, message)
        if key in self._seen:
            return
        self._seen.add(key)
        self.errors.append(CheckError(file=file, line=max(0, int(line)),
                                      rule=rule, message=message))

    def _read(self, path: Path) -> str:
        return path.read_text(encoding="utf-8-sig", errors="replace")

    def _collect_markdown(self) -> list[Path]:
        found: list[Path] = []
        for dirpath, dirnames, filenames in os.walk(self.root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in sorted(filenames):
                if not name.lower().endswith((".md", ".markdown")):
                    continue
                path = Path(dirpath) / name
                try:
                    if path.stat().st_size <= MAX_MARKDOWN_BYTES:
                        found.append(path)
                except OSError:
                    continue
        return sorted(found)

    def _collect_text(self) -> list[Path]:
        found: list[Path] = []
        for dirpath, dirnames, filenames in os.walk(self.root):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in sorted(filenames):
                path = Path(dirpath) / name
                suffix = path.suffix.lower()
                if suffix not in TEXT_SUFFIXES and suffix != "":
                    continue
                try:
                    if path.stat().st_size > MAX_TEXT_BYTES:
                        continue
                except OSError:
                    continue
                found.append(path)
        return sorted(found)

    def _first_two_lines(self, path: Path) -> str:
        try:
            text = self._read(path)
        except OSError:
            return ""
        return "\n".join(text.splitlines()[:2]).casefold()

    def is_generated(self, path: Path) -> bool:
        head = self._first_two_lines(path)
        return any(marker in head for marker in GENERATED_MARKERS)

    def is_ignored(self, path: Path) -> bool:
        try:
            return bool(IGNORE_RE.search(self._read(path)))
        except OSError:
            return False

    # ------------------------------------------------------------------
    # rule 1: README table of contents
    # ------------------------------------------------------------------
    def check_toc(self) -> None:
        readme = self.root / "README.md"
        if not readme.is_file():
            self.add("README.md", 1, "toc", "thieu README.md")
            return
        readme_rel = self.rel(readme)
        lines = self._read(readme).splitlines()

        toc_start: int | None = None
        for index, line in enumerate(lines):
            heading = HEADING_RE.match(line)
            if heading and any(
                word in heading.group(2).casefold() for word in TOC_WORDS
            ):
                toc_start = index
                break
        if toc_start is None:
            self.add(readme_rel, 1, "toc",
                     f"khong tim thay tieu de '{TOC_WORDS[0]}'")
            return

        toc_end = len(lines)
        for index in range(toc_start + 1, len(lines)):
            if HEADING_RE.match(lines[index]):
                toc_end = index
                break

        toc_targets: set[str] = set()
        for index in range(toc_start + 1, toc_end):
            source = INLINE_CODE_RE.sub("", lines[index])
            for raw in LINK_RE.findall(source):
                target = parse_link_target(raw)
                if target is None:
                    continue
                self._toc_links.add((readme_rel, index + 1, target))
                resolved = self._resolve_link(readme, target)
                if resolved is None:
                    continue
                toc_targets.add(os.path.normcase(str(resolved)))
                if not resolved.exists():
                    self.add(
                        readme_rel,
                        index + 1,
                        "toc",
                        f"muc luc tro toi file khong ton tai: {target}",
                    )

        docs_dir = self.root / "docs"
        if docs_dir.is_dir():
            for doc in sorted(docs_dir.glob("*.md")):
                if not doc.is_file():
                    continue
                if self.is_generated(doc) or self.is_ignored(doc):
                    continue
                key = os.path.normcase(str(doc.resolve()))
                if key not in toc_targets:
                    self.add(
                        readme_rel,
                        toc_start + 1,
                        "toc",
                        f"thieu file trong muc luc: {self.rel(doc)}",
                    )

    # ------------------------------------------------------------------
    # rule 2: registry IDs
    # ------------------------------------------------------------------
    def _load_registries(self) -> dict[str, set[str] | None]:
        loaded: dict[str, set[str] | None] = {}
        missing: set[str] = set()
        for prefix, rel_doc, id_re, _ref_re in REGISTRIES:
            doc = self.root / rel_doc
            if not doc.is_file():
                if rel_doc not in missing:
                    missing.add(rel_doc)
                    self.add(rel_doc, 1, "id-ref",
                             f"thieu file so lieu ID: {rel_doc}")
                loaded[prefix] = None
                continue
            ids: set[str] = set()
            try:
                lines = self._read(doc).splitlines()
            except OSError as exc:
                self.add(rel_doc, 1, "id-ref", f"khong doc duoc file: {exc}")
                loaded[prefix] = None
                continue
            for line in lines:
                if "|" not in line:
                    continue
                cells = split_cells(line)
                if cells and id_re.fullmatch(cells[0]):
                    ids.add(cells[0])
            if not ids:
                self.add(rel_doc, 1, "id-ref",
                         f"khong tim thay bang ID cho {prefix}")
                loaded[prefix] = None
            else:
                loaded[prefix] = ids
        return loaded

    def check_ids(self) -> None:
        registries = self._load_registries()
        rules = {prefix: (rel_doc, ref_re)
                 for prefix, rel_doc, _id_re, ref_re in REGISTRIES}
        for path in self.text_files:
            try:
                lines = self._read(path).splitlines()
            except OSError:
                continue
            file_rel = self.rel(path)
            for line_no, line in enumerate(lines, start=1):
                for prefix, ids in registries.items():
                    if not ids:
                        continue
                    rel_doc, ref_re = rules[prefix]
                    for match in ref_re.finditer(line):
                        found = match.group(0)
                        if found not in ids:
                            self.add(
                                file_rel,
                                line_no,
                                "id-ref",
                                f"ma {found} khong co trong {rel_doc}",
                            )

    # ------------------------------------------------------------------
    # rule 3: relative markdown links
    # ------------------------------------------------------------------
    def _resolve_link(self, source: Path, target: str) -> Path | None:
        if not target:
            return None
        if target.startswith("/"):
            return None
        candidate = Path(target)
        if candidate.is_absolute() or candidate.drive:
            return None
        return Path(os.path.normpath(source.parent / candidate))

    def check_links(self) -> None:
        for path in self.markdown_files:
            try:
                lines = self._read(path).splitlines()
            except OSError:
                continue
            file_rel = self.rel(path)
            mask = fence_mask(lines)
            for index, line in enumerate(lines):
                if mask[index]:
                    continue
                source = INLINE_CODE_RE.sub("", line)
                for raw in LINK_RE.findall(source):
                    target = parse_link_target(raw)
                    if target is None:
                        continue
                    if (file_rel, index + 1, target) in self._toc_links:
                        continue
                    if not target.lower().endswith(".md"):
                        continue
                    resolved = self._resolve_link(path, target)
                    if resolved is None:
                        continue
                    if not resolved.exists():
                        self.add(file_rel, index + 1, "link",
                                 f"link chet: {target}")

    # ------------------------------------------------------------------
    # rule 4: markdown table cell counts
    # ------------------------------------------------------------------
    def check_tables(self) -> None:
        for path in self.markdown_files:
            try:
                lines = self._read(path).splitlines()
            except OSError:
                continue
            file_rel = self.rel(path)
            mask = fence_mask(lines)
            index = 0
            while index < len(lines):
                line = lines[index]
                if mask[index] or not _is_table_row(line):
                    index += 1
                    continue
                if index + 1 >= len(lines) or mask[index + 1]:
                    index += 1
                    continue
                separator = lines[index + 1]
                if not _is_table_row(separator) or not is_separator(separator):
                    index += 1
                    continue

                header = split_cells(line)
                sep_cells = split_cells(separator)
                if not header or not sep_cells:
                    index += 1
                    continue
                self.table_count += 1
                width = len(header)
                if len(sep_cells) != width:
                    self.add(
                        file_rel,
                        index + 2,
                        "table",
                        f"dong phan cach co {len(sep_cells)} o, "
                        f"tieu de co {width} o",
                    )

                row = index + 2
                while row < len(lines):
                    if mask[row] or not _is_table_row(lines[row]):
                        break
                    if is_separator(lines[row]):
                        row += 1
                        continue
                    cells = split_cells(lines[row])
                    if len(cells) != width:
                        self.add(
                            file_rel,
                            row + 1,
                            "table",
                            f"dong co {len(cells)} o, tieu de co {width} o",
                        )
                    row += 1
                index = max(row, index + 1)

    # ------------------------------------------------------------------
    # rule 5: generated files carry a marker
    # ------------------------------------------------------------------
    def check_generated(self) -> None:
        generated_dir = self.root / "spec" / "generated"
        if not generated_dir.is_dir():
            return
        for dirpath, dirnames, filenames in os.walk(generated_dir):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in sorted(filenames):
                if name.startswith("."):
                    # .gitkeep and friends are not generated content.
                    continue
                path = Path(dirpath) / name
                suffix = path.suffix.lower()
                if suffix in {".json", ".csv"}:
                    # Machine-readable formats cannot carry a comment marker.
                    self.generated_skipped += 1
                    continue
                head = self._first_two_lines(path)
                if not any(marker in head for marker in GENERATED_MARKERS):
                    self.add(
                        self.rel(path),
                        1,
                        "generated",
                        "file sinh thieu nhan AUTOGENERATED/(sinh tu dong)",
                    )

    # ------------------------------------------------------------------
    # run
    # ------------------------------------------------------------------
    def run(self) -> None:
        checks = (
            ("toc", self.check_toc),
            ("id-ref", self.check_ids),
            ("link", self.check_links),
            ("table", self.check_tables),
            ("generated", self.check_generated),
        )
        for label, function in checks:
            try:
                function()
            except Exception as exc:  # defensive: never crash on real docs
                self.add(
                    ".",
                    0,
                    "internal",
                    f"loi noi bo trong {label}: {type(exc).__name__}: {exc}",
                )

    def sorted_errors(self) -> list[CheckError]:
        return sorted(self.errors)

    def result(self) -> dict[str, object]:
        errors = self.sorted_errors()
        return {
            "root": str(self.root),
            "ok": not errors,
            "stats": {
                "markdown_files": len(self.markdown_files),
                "tables": self.table_count,
                "generated_marker_exempt": self.generated_skipped,
                "errors": len(errors),
            },
            "errors": [asdict(error) for error in errors],
        }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Check documentation consistency (stdlib only)."
    )
    parser.add_argument(
        "--root", default=".", help="repository root (default: current dir)"
    )
    parser.add_argument(
        "--json", action="store_true", help="print the result as ASCII JSON"
    )
    args = parser.parse_args(argv)

    root = Path(args.root)
    if not root.is_dir():
        print(f"LOI: {_ascii(root)}:0 khong phai thu muc")
        return 2

    checker = Checker(root)
    checker.run()
    result = checker.result()

    if args.json:
        print(json.dumps(result, ensure_ascii=True, indent=2, sort_keys=True))
    else:
        for error in checker.sorted_errors():
            print(error.text())
        if result["ok"]:
            print(
                f"OK: {result['stats']['markdown_files']} file markdown, "
                f"{result['stats']['tables']} bang, khong co loi"
            )
        else:
            # Every "LOI:" line above carries file:line; the total is extra.
            print(f"TONG: {result['stats']['errors']} loi")

    return 0 if result["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
